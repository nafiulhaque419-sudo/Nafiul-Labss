function loadLevel(){
  for(let y=0; y<size; y++){
    for(let x=0; x<size; x++){
      cells[y][x].className="cell";
    }
  }
  
  for(let y=0; y<size; y++){
    for(let x=0; x<size; x++){
      if(level[y][x]==="."){
        continue;
      }
      
      if(level[y][x]==="#"){
        cells[y][x].className="wall";
      }
      
      if(level[y][x]==="P"){
        cells[y][x].className="hero";
      }
      
      if(level[y][x]==="B"){
        cells[y][x].className="box";
      }
      
      if(level[y][x]==="T"){
        cells[y][x].className="target";
      }
      
      if(level[y][x]==="*"){
        cells[y][x].className="complete";
      }
    }
    
    levelVal.innerText=`Level: ${currLevel+1}`;
  }
}

const directions = {
  right: { dx: 1, dy: 0 },
  left:  { dx: -1, dy: 0 },
  up:    { dx: 0, dy: -1 },
  down:  { dx: 0, dy: 1 }
};

function move(direction){

  let x, y;

  // Find hero
  for(let i=0;i<size;i++){
    for(let j=0;j<size;j++){
      if(level[i][j]==="P" || level[i][j]==="+"){
        y=i;
        x=j;
        break;
      }
    }
  }

  const {dx,dy}=directions[direction];

  const nx=x+dx;
  const ny=y+dy;

  // Outside board
  if(nx<0 || nx>=size || ny<0 || ny>=size){
    return;
  }

  // Wall
  if(level[ny][nx]==="#"){
    return;
  }

  // Box
  if(level[ny][nx] === "B" || level[ny][nx] === "*"){

    const bx = nx + dx;
    const by = ny + dy;

    if(
        bx < 0 || bx >= size ||
        by < 0 || by >= size ||
        level[by][bx] === "#" ||
        level[by][bx] === "B" ||
        level[by][bx] === "*"
    ){
        return;
    }

    // Remove box from old position
    cells[ny][nx].classList.remove("box");

    if(level[ny][nx] === "*"){
        level[ny][nx] = "T";
        cells[ny][nx].classList.remove("complete");
        cells[ny][nx].classList.add("target");
    }else{
        level[ny][nx] = ".";
    }

    // Place box at new position
    if(level[by][bx] === "T"){
        level[by][bx] = "*";
        cells[by][bx].classList.add("complete");
    }else{
        level[by][bx] = "B";
    }

    cells[by][bx].classList.add("box");
}

  // Remove hero from old position
  cells[y][x].classList.remove("hero");

  if(level[y][x]==="+"){
    level[y][x]="T";
  }else{
    level[y][x]=".";
  }

  // Hero enters target
  if(level[ny][nx]==="T"){
    level[ny][nx]="+";
  }else{
    level[ny][nx]="P";
  }

  cells[ny][nx].classList.add("hero");

  if(!cells[y][x].classList.contains("cell")){
    cells[y][x].classList.add("cell");
  }

  if(isComplete()){
    if(currLevel<levels.length-1){
      currLevel++;
      copyLevel(currLevel);
      loadLevel();
    }
    else{
      alert("You Win!");
    }
  }
}

function isComplete(){
  let targets=[];
  
  for(let i=0; i<size; i++){
    for(let j=0; j<size; j++){
      if(level[i][j]==="T" || level[i][j]==="+"){
        targets.push({
          y:i,
          x:j
        });
      }
    }
  }
  
  let success=0;
  
  for(let target of targets){
    if(level[target.y][target.x]==="B"){
      success++;
    }
  }
  
  if(success===targets.length){
    return true;
  }
  
  return false;
}

